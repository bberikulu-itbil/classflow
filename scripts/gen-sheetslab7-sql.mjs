// Writes supabase/060_informatics7_sheets.sql from src/lessons/sheetsLab7. Run: node scripts/gen-sheetslab7-sql.mjs
import { build } from 'esbuild'; import { writeFileSync } from 'node:fs'; import { tmpdir } from 'node:os';
const out = `${tmpdir()}/sheetslab7-gen.mjs`;
await build({ entryPoints: ['src/lessons/sheetsLab7/index.ts'], bundle: true, format: 'esm', outfile: out, logLevel: 'error' });
const { SHEETS7_LESSONS: L, SHEETS7_LESSONS_DATA: D, SHEETS7_COURSE: C, SHEETS7_MODULE: MOD } = await import(out);
const q = s => { if (s.includes('$s7$')) throw new Error('dollar tag clash'); return `$s7$${s}$s7$`; };
const rows = L.map((m, i) => { const l = D[m.id]; return `    (${q(l.title)}, ${q(l.subject)}, ${i}, ${q(JSON.stringify(l.plan))}::jsonb, ${q(JSON.stringify(l.terms))}::jsonb, ${q(JSON.stringify(l.slides))}::jsonb)`; });
writeFileSync('supabase/060_informatics7_sheets.sql', `-- Migration 060: Informatics 7th grade - the course "${C.title}" with the 8 lessons of textbook Chapter 3 (2nd quarter: tables and spreadsheets), kk/ru/en.
-- GENERATED by scripts/gen-sheetslab7-sql.mjs from src/lessons/sheetsLab7: edit the TypeScript, then regenerate.
-- Needs 041_sheet_criteria.sql. Idempotent: the course is found by title, the module by title, lessons by module position (or title).

do $informatics7$
declare
  v_school uuid; v_owner uuid; v_course uuid; v_module uuid; v_lesson uuid; v_spec record;
begin
  -- the course belongs to the teacher who owns the 8th-grade course (so it shows in that teacher's library)
  select c.owner_id, c.school_id into v_owner, v_school from public.cf_curr_courses c
  where c.title in ('Informatics 8th grade', 'Информатика 8-сынып', 'Информатика 8') order by c.created_at limit 1;
  if v_owner is null then select p.id, p.school_id into v_owner, v_school from public.profiles p where p.role in ('teacher', 'admin') order by p.created_at limit 1; end if;
  if v_owner is null then raise exception 'Мұғалім немесе әкімші аккаунты табылмады'; end if;

  select id into v_course from public.cf_curr_courses where title = ${q(C.title)} and school_id = v_school limit 1;
  if v_course is null then
    insert into public.cf_curr_courses (school_id, owner_id, title, subject, grade)
    values (v_school, v_owner, ${q(C.title)}, ${q(C.subject)}, ${C.grade}) returning id into v_course;
  end if;

  select id into v_module from public.cf_curr_modules where course_id = v_course and title = ${q(MOD.title)} limit 1;
  if v_module is null then
    insert into public.cf_curr_modules (course_id, title, position, kind, quarter, grade)
    values (v_course, ${q(MOD.title)}, ${MOD.position}, 'lesson', ${MOD.quarter}, ${MOD.grade}) returning id into v_module;
  end if;

  for v_spec in select * from (values
${rows.join(',\n')}
  ) as t(title, subject, position, plan, terms, slides)
  loop
    select cl.lesson_id into v_lesson from public.cf_curr_lessons cl where cl.module_id = v_module and cl.position = v_spec.position limit 1;
    -- by title only a lesson that sits in no module: a lesson of another module with the same title is somebody else's work and must not be overwritten
    if v_lesson is null then select l.id into v_lesson from public.cf_lessons l where l.school_id = v_school and l.title = v_spec.title and not exists (select 1 from public.cf_curr_lessons x where x.lesson_id = l.id) limit 1; end if;
    if v_lesson is null then
      insert into public.cf_lessons (school_id, owner_id, title, subject, plan, slides, terms)
      values (v_school, v_owner, v_spec.title, v_spec.subject, v_spec.plan, v_spec.slides, v_spec.terms) returning id into v_lesson;
    else
      update public.cf_lessons set title = v_spec.title, subject = v_spec.subject, plan = v_spec.plan, slides = v_spec.slides, terms = v_spec.terms, updated_at = now() where id = v_lesson;
    end if;
    insert into public.cf_curr_lessons (lesson_id, module_id, position) values (v_lesson, v_module, v_spec.position)
    on conflict (lesson_id) do update set module_id = excluded.module_id, position = excluded.position;
    v_lesson := null;
  end loop;
end;
$informatics7$;
`);
