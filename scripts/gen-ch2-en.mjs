// Writes supabase/051_informatics_10_ch2_en.sql: the English version (`en` block) of the slides of lessons 2.1-2.5.
// The Kazakh slides come from gen-ch2.mjs (+ the pictures of gen-ch2-img.mjs and the interactive slides of gen-ch2-sim.mjs), the texts from ch2-en-dict.mjs.
// Notes stay Kazakh (teacher only), accept lists and answers are copied from the Kazakh slide. Run: node scripts/gen-ch2-en.mjs
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { LESSONS } from './gen-ch2.mjs';
import { S } from './gen-ch2-sim.mjs';
import { IMG } from './gen-ch2-img.mjs';
import { EN } from './ch2-en-dict.mjs';
import { enBlock } from './ch2-en-walk.mjs';

const CYR = /[Ѐ-ӿ]/;
const missing = new Set();
const tr = s => { if (!CYR.test(s)) return s; if (!(s in EN)) { missing.add(s); return s; } return EN[s]; };
const used = new Set();
const trU = s => { used.add(s); return tr(s); };

const items = []; // [lesson, kk title, en block]
const imgOf = (n, t) => IMG.find(([l, st]) => l === n && st === t);
for (const [n, L] of Object.entries(LESSONS)) {
  const titles = L.slides.map(s => s.title);
  for (const s of L.slides) {
    const im = imgOf(n, s.title);
    items.push([n, s.title, enBlock(s, trU, { dropCode: im && im[4], alt: im && trU(im[3]) })]);
  }
}
for (const [n, after, s] of S) {
  const im = imgOf(n, s.title);
  items.push([n, s.title, enBlock(s, trU, { dropCode: im && im[4] })]);
}
if (missing.size) { console.error('MISSING in ch2-en-dict.mjs:\n' + [...missing].map(x => '  ' + x).join('\n')); process.exit(1); }
for (const k of Object.keys(EN)) if (CYR.test(k) && !used.has(k)) console.warn('unused dictionary entry:', k);
// the picture slides of the interactive gates (2.3, 2.5 `logic`) have no text to translate beyond title/prompt; the base slides must keep their own fields
const key = (n, t) => n + '|' + t; const seen = new Set();
for (const [n, t] of items) { assert(!seen.has(key(n, t)), 'duplicate title in lesson ' + n + ': ' + t); seen.add(key(n, t)); }
const q = s => { if (/\$sl\$/.test(s)) throw new Error('quote'); return `$sl$${s}$sl$`; };
writeFileSync('supabase/051_informatics_10_ch2_en.sql', `-- Migration 051: English version (slide.en) of the 10 сынып informatics lessons 2.1-2.5 (046 + pictures 049 + interactive slides 050), and slide.ask on the two gate slides of 050.
-- GENERATED by scripts/gen-ch2-en.mjs. Idempotent: sets slide.en by lesson number and Kazakh slide title; a slide that is not found is skipped, a lesson that is not found raises.

do $ch2en$
declare r record; n int := 0; m uuid;
begin
  select cm.id into m from public.cf_curr_modules cm join public.cf_curr_courses cc on cc.id = cm.course_id
   where cc.subject = 'Информатика' and cc.grade = 10 and cm.title like '2-тарау.%';
  if m is null then raise exception 'chapter 2 module not found'; end if;
  for r in select * from (values
${items.map(([n, t, e]) => `    (${q(n)}, ${q(t)}, ${q(JSON.stringify(e))}::jsonb)`).join(',\n')}
  ) as t(les, stitle, en)
  loop
    update public.cf_lessons l set updated_at = now(), slides = (
      select jsonb_agg(case when s->>'title' = r.stitle then s || jsonb_build_object('en', r.en) else s end order by o)
      from jsonb_array_elements(l.slides) with ordinality a(s, o))
    where l.id in (select lesson_id from public.cf_curr_lessons where module_id = m) and l.title like r.les || ' %'
      and exists (select 1 from jsonb_array_elements(l.slides) s where s->>'title' = r.stitle);
    get diagnostics n = row_count;
    if n = 0 then raise exception 'lesson % : slide "%" not found', r.les, r.stitle; end if;
  end loop;

  -- the two gate slides of 050 get a question box (slide.ask), so the student has a place to write an answer
  update public.cf_lessons l set updated_at = now(), slides = (
    select jsonb_agg(case when s->>'type' = 'logic' and s->>'title' in ($sl$Логикалық элементті сына$sl$, $sl$Вентильдермен тәжірибе$sl$) then s || '{"ask": true}'::jsonb else s end order by o)
    from jsonb_array_elements(l.slides) with ordinality a(s, o))
  where l.id in (select lesson_id from public.cf_curr_lessons where module_id = m)
    and exists (select 1 from jsonb_array_elements(l.slides) s where s->>'type' = 'logic' and s->>'title' in ($sl$Логикалық элементті сына$sl$, $sl$Вентильдермен тәжірибе$sl$));
end;
$ch2en$;
`);
console.log('en blocks', items.length);
