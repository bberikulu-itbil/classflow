export function isDatabasesLessonId(id: string): boolean {
  return id in DATABASES_LESSONS_DATA || DATABASES_LESSONS_META.some(m => m.id === id);
}

export async function loadDatabasesLesson(id: string): Promise<{ id: string; title: string; subject: string; slides: any[]; terms?: any[]; plan?: any } | null> {
  const lesson = DATABASES_LESSONS_DATA[id];
  if (!lesson) return null;
  return {
    id: lesson.id,
    title: lesson.title,
    subject: lesson.subject,
    slides: lesson.slides,
    terms: lesson.terms,
    plan: lesson.plan,
  };
}
