  title text, subject text, position int,
  plan jsonb, terms jsonb, slides jsonb
)
  loop
    -- Look for existing lesson with this title in this school
    select id into v_lesson
    from public.cf_lessons
    where title = v_spec.title
      and school_id = v_school
    limit 1;

    if v_lesson is null then
      insert into public.cf_lessons (school_id, owner_id, title, subject, plan, slides, terms)
      values (v_school, v_owner, v_spec.title, v_spec.subject, v_spec.plan, v_spec.slides, v_spec.terms)
      returning id into v_lesson;
    else
      update public.cf_lessons
      set owner_id = v_owner, subject = v_spec.subject, plan = v_spec.plan, slides = v_spec.slides, terms = v_spec.terms, updated_at = now()
      where id = v_lesson;
    end if;

    -- Place lesson in the Database basics module
    insert into public.cf_curr_lessons (lesson_id, module_id, position)
    values (v_lesson, v_module, v_spec.position)
    on conflict (lesson_id) do update
      set module_id = excluded.module_id, position = excluded.position;

    v_lesson := null;
  end loop;
end;
